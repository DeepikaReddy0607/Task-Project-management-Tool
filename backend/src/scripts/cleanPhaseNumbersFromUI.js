for (const { file, replacements } of filesToClean) {
    if (!fs.existsSync(file)) {
        console.error("File not found:", file);
        continue;
    }
    let content = fs.readFileSync(file, "utf8");
    const isCrlf = content.includes("\r\n");
    let code = content.replace(/\r\n/g, "\n");

    for (const [target, replacement] of replacements) {
        if (code.includes(target)) {
            code = code.replace(target, replacement);
            console.log(`[REPLACED] in ${file}: "${target}" -> "${replacement}"`);
        } else {
            console.warn(`[NOT FOUND] in ${file}: "${target}"`);
        }
    }

    if (isCrlf) code = code.replace(/\n/g, "\r\n");
    fs.writeFileSync(file, code, "utf8");
}

console.log("Phase numbers cleanup complete.");
